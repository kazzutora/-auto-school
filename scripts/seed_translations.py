def _apply(queryset: Any, key_field: str, table: dict[str, dict[str, tuple[str, str]]]) -> int:
    """Write the _ru and _uk columns for the rows named in the table."""
    written = 0
    for row in queryset:
        fields = table.get(getattr(row, key_field))
        if not fields:
            continue
        columns = []
        for name, (ru, uk) in fields.items():
            setattr(row, f"{name}_ru", ru)
            setattr(row, f"{name}_uk", uk)
            columns += [f"{name}_ru", f"{name}_uk"]
        row.save(update_fields=columns)
        written += 1
    return written


